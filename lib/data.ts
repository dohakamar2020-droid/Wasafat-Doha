  push(recipes.filter(x => x.slug !== r.slug && x.mainIngredients.some(i => r.mainIngredients.includes(i)) && x.category === r.category).sort((a,b)=>b.views-a.views)[0], `نفس المكوّن الأساسي (${r.mainIngredients[0]}) بشكل تاني`);
